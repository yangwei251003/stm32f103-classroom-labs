//=====================OLED引脚配置=====================
#define OLED_SDA_PIN  GPIO_Pin_7
#define OLED_SCL_PIN  GPIO_Pin_6
#define OLED_PORT     GPIOB
#define OLED_ADDR     0x78    //黑屏就改成0x7A

#define OLED_SDA_H()  GPIO_SetBits(OLED_PORT,OLED_SDA_PIN)
#define OLED_SDA_L()  GPIO_ResetBits(OLED_PORT,OLED_SDA_PIN)
#define OLED_SCL_H()  GPIO_SetBits(OLED_PORT,OLED_SCL_PIN)
#define OLED_SCL_L()  GPIO_ResetBits(OLED_PORT,OLED_SCL_PIN)

//=====================I2C底层函数=====================
void OLED_I2C_Start(void)
{
    OLED_SDA_H();
    OLED_SCL_H();
    Delay_us(4);
    OLED_SDA_L();
    Delay_us(4);
    OLED_SCL_L();
}

void OLED_I2C_Stop(void)
{
    OLED_SDA_L();
    OLED_SCL_H();
    Delay_us(4);
    OLED_SDA_H();
    Delay_us(4);
}

u8 OLED_I2C_WaitAck(void)
{
    u8 ack = 0;
    OLED_SDA_H();
    OLED_SCL_H();
    Delay_us(4);
    while(GPIO_ReadInputDataBit(OLED_PORT,OLED_SDA_PIN))
    {
        ack++;
        if(ack > 250)
        {
            OLED_I2C_Stop();
            return 1;
        }
    }
    OLED_SCL_L();
    return 0;
}

void OLED_I2C_WriteByte(u8 dat)
{
    u8 i;
    for(i = 0; i < 8; i++)
    {
        OLED_SCL_L();
        Delay_us(2);
        if(dat & 0x80)
            OLED_SDA_H();
        else
            OLED_SDA_L();
        dat <<= 1;
        Delay_us(2);
        OLED_SCL_H();
        Delay_us(2);
    }
}

//发送命令
void OLED_Write_Cmd(u8 cmd)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte(OLED_ADDR << 1);
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(0x00);
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(cmd);
    OLED_I2C_WaitAck();
    OLED_I2C_Stop();
}

//发送显示数据
void OLED_Write_Data(u8 dat)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte(OLED_ADDR << 1);
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(0x40);
    OLED_I2C_WaitAck();
    OLED_I2C_WriteByte(dat);
    OLED_I2C_WaitAck();
    OLED_I2C_Stop();
}

//设置光标坐标
void OLED_Set_Pos(u8 x, u8 y)
{
    OLED_Write_Cmd(0xb0 + y);
    OLED_Write_Cmd(((x & 0xf0) >> 4) | 0x10);
    OLED_Write_Cmd(x & 0x0f);
}

//全屏清屏
void OLED_Clear(void)
{
    u8 y, x;
    for(y = 0; y < 8; y++)
    {
        OLED_Write_Cmd(0xb0 + y);
        OLED_Write_Cmd(0x00);
        OLED_Write_Cmd(0x10);
        for(x = 0; x < 128; x++)
            OLED_Write_Data(0x00);
    }
}

