//显示单个数字 x横坐标 y页号 num数字0~9
void OLED_ShowNum(u8 x, u8 y, u8 num)
{
    u8 t;
    OLED_Set_Pos(x, y);
    for(t = 0; t < 16; t++)
        OLED_Write_Data(num8x16[num][t]);
    OLED_Set_Pos(x, y+1);
    for(t = 16; t < 32; t++)
        OLED_Write_Data(num8x16[num][t]);
}

//OLED硬件初始化
void OLED_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStruct;
    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB, ENABLE);

    GPIO_InitStruct.GPIO_Pin = OLED_SDA_PIN | OLED_SCL_PIN;
    GPIO_InitStruct.GPIO_Mode = GPIO_Mode_Out_PP;
    GPIO_InitStruct.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(OLED_PORT, &GPIO_InitStruct);

    OLED_SDA_H();
    OLED_SCL_H();
    Delay_ms(100);

    OLED_Write_Cmd(0xAE); //关闭显示
    OLED_Write_Cmd(0xD5); //时钟分频
    OLED_Write_Cmd(0x80);
    OLED_Write_Cmd(0xA8); //多路复用
    OLED_Write_Cmd(0x3F);
    OLED_Write_Cmd(0xD3); //显示偏移
    OLED_Write_Cmd(0x00);
    OLED_Write_Cmd(0x40); //起始行
    OLED_Write_Cmd(0x8D); //电荷泵
    OLED_Write_Cmd(0x14);
    OLED_Write_Cmd(0x20); //内存模式
    OLED_Write_Cmd(0x02);
    OLED_Write_Cmd(0xA1); //段重映射
    OLED_Write_Cmd(0xC8); //COM扫描方向
    OLED_Write_Cmd(0xDA); //COM硬件配置
    OLED_Write_Cmd(0x12);
    OLED_Write_Cmd(0x81); //对比度
    OLED_Write_Cmd(0xCF);
    OLED_Write_Cmd(0xD9); //预充电
    OLED_Write_Cmd(0xF1);
    OLED_Write_Cmd(0xDB); //VCOMH
    OLED_Write_Cmd(0x40);
    OLED_Write_Cmd(0xA4); //跟随RAM内容
    OLED_Write_Cmd(0xA6); //正常显示
    OLED_Write_Cmd(0xAF); //开启OLED

    OLED_Clear();
}

